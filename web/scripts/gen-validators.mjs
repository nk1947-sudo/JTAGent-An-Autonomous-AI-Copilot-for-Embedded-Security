// Generates CSP-safe validators (no runtime eval) from the authoritative backend schema.
// Input: ../contracts/openapi.json (generated from the Pydantic models). Output: src/generated/validators.js.
// Run automatically by `npm run build`; never edit the output by hand.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const NAMES = ['AttackPlan', 'DebuggerAdvice', 'PatchPreview', 'Readiness', 'BundleResult'];
const openapi = JSON.parse(readFileSync(new URL('../../contracts/openapi.json', import.meta.url), 'utf8'));
const missing = NAMES.filter(n => !openapi.components.schemas[n]);
if (missing.length) throw new Error('schemas missing from contracts/openapi.json: ' + missing.join(', '));

const ajv = new Ajv2020.default({ strict: false, allErrors: true, validateFormats: false, code: { source: true, esm: true } });
ajv.addSchema({ $id: 'jtagent-openapi', ...openapi });
let code = standaloneCode.default(ajv, Object.fromEntries(NAMES.map(n => [n, `jtagent-openapi#/components/schemas/${n}`])));
// Ajv emits a CommonJS require for its helper; turn it into an ES import so the browser bundle works.
const helper = /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/;
const found = code.match(helper);
if (found) code = "import ucs2length from 'ajv/dist/runtime/ucs2length.js';" + String.fromCharCode(10) + code.replace(helper, `const ${found[1]} = ucs2length;`);
if (code.includes('require(')) throw new Error('generated validators still use require()');
const operations = openapi.components.schemas.DebuggerAction.properties.operation.enum;
const footer = `\nexport const validators = { ${NAMES.join(', ')} };\nexport const KNOWN_OPERATIONS = ${JSON.stringify(operations)};\n`;
mkdirSync(new URL('../src/generated/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/generated/validators.js', import.meta.url), '// @generated by scripts/gen-validators.mjs from contracts/openapi.json. Do not edit.\n// @ts-nocheck\n' + code + footer);
console.log('generated validators for', NAMES.join(', '));
